package com.apg.promociones.apg_api.service;

import com.apg.promociones.apg_api.exception.BadRequestException;
import com.apg.promociones.apg_api.exception.ResourceNotFoundException;
import com.apg.promociones.apg_api.model.Coupon;
import com.apg.promociones.apg_api.model.User;
import com.apg.promociones.apg_api.model.enums.CouponStatus;
import com.apg.promociones.apg_api.repository.CouponRepository;
import com.apg.promociones.apg_api.util.QrCodeGenerator;
import com.google.zxing.BinaryBitmap;
import com.google.zxing.client.j2se.BufferedImageLuminanceSource;
import com.google.zxing.common.HybridBinarizer;
import com.google.zxing.qrcode.QRCodeReader;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;
import org.springframework.security.access.AccessDeniedException;

import javax.imageio.ImageIO;
import java.awt.image.BufferedImage;
import java.io.ByteArrayInputStream;
import java.util.Optional;

import static org.junit.jupiter.api.Assertions.assertArrayEquals;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.mockito.Mockito.verifyNoInteractions;
import static org.mockito.Mockito.when;

@ExtendWith(MockitoExtension.class)
class CouponQrServiceTest {

    private static final String COUPON_HASH = "a3f1b2c4-d5e6-7890-abcd-ef1234567890";
    private static final byte[] PNG_SIGNATURE = {(byte) 0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A};

    @Mock
    private CouponRepository couponRepository;

    private CouponQrService couponQrService;
    private Coupon coupon;

    @BeforeEach
    void setUp() {
        couponQrService = new CouponQrService(couponRepository, new QrCodeGenerator());

        User owner = User.builder()
                .id(10)
                .firstName("Carlos")
                .lastName("Perez")
                .email("carlos.perez@example.com")
                .build();

        coupon = Coupon.builder()
                .id(15)
                .user(owner)
                .status(CouponStatus.UNUSED)
                .couponHash(COUPON_HASH)
                .build();
    }

    @Test
    void generatesScannablePngContainingOnlyPersistedCouponHashForOwner() throws Exception {
        when(couponRepository.findById(15)).thenReturn(Optional.of(coupon));

        byte[] pngBytes = couponQrService.generateCouponQrPng(15, 10);

        assertNotNull(pngBytes);
        byte[] header = new byte[PNG_SIGNATURE.length];
        System.arraycopy(pngBytes, 0, header, 0, PNG_SIGNATURE.length);
        assertArrayEquals(PNG_SIGNATURE, header);

        String decodedPayload = decodeQrFromPng(pngBytes);
        assertEquals(COUPON_HASH, decodedPayload);
        assertFalse(decodedPayload.contains("carlos"));
        assertFalse(decodedPayload.contains("15"));
    }

    @Test
    void throwsBadRequestWhenCouponIdIsNullOrNonPositive() {
        assertThrows(BadRequestException.class, () -> couponQrService.generateCouponQrPng(null, 10));
        assertThrows(BadRequestException.class, () -> couponQrService.generateCouponQrPng(0, 10));
        assertThrows(BadRequestException.class, () -> couponQrService.generateCouponQrPng(-5, 10));
        verifyNoInteractions(couponRepository);
    }

    @Test
    void throwsNotFoundWhenCouponDoesNotExist() {
        when(couponRepository.findById(999)).thenReturn(Optional.empty());

        ResourceNotFoundException ex = assertThrows(
                ResourceNotFoundException.class,
                () -> couponQrService.generateCouponQrPng(999, 10));

        assertEquals("Coupon not found.", ex.getMessage());
    }

    @Test
    void throwsAccessDeniedWhenCouponBelongsToAnotherUser() {
        when(couponRepository.findById(15)).thenReturn(Optional.of(coupon));

        assertThrows(AccessDeniedException.class, () -> couponQrService.generateCouponQrPng(15, 99));
    }

    private static String decodeQrFromPng(byte[] pngBytes) throws Exception {
        BufferedImage image = ImageIO.read(new ByteArrayInputStream(pngBytes));
        assertNotNull(image, "Generated bytes must decode as a valid PNG image.");
        BinaryBitmap bitmap = new BinaryBitmap(new HybridBinarizer(new BufferedImageLuminanceSource(image)));
        return new QRCodeReader().decode(bitmap).getText();
    }
}
