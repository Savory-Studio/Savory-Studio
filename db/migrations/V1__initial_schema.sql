-- =============================================================
-- V1: Initial schema — enums, users, restaurants, discounts, coupon
-- Covers: APG-20, APG-24, APG-25, APG-31
-- Idempotent: safe to run on an existing database
-- =============================================================

-- Enums
DO $$ BEGIN
    CREATE TYPE discount_status_enum AS ENUM ('Active', 'Suspended', 'Finished');
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

DO $$ BEGIN
    CREATE TYPE discount_type_enum AS ENUM ('PERCENTAGE', 'FIXED_VALUE', 'IXJ');
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

DO $$ BEGIN
    CREATE TYPE coupon_status_enum AS ENUM ('UNUSED', 'USED');
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

-- Existing installations retain their access policies. Fresh tables are served by
-- Spring through its database role; public API roles get no implicit row access.
DO $$
DECLARE
    table_name text;
    new_tables text[];
BEGIN
    SELECT array_agg(name) INTO new_tables
    FROM unnest(ARRAY['users', 'restaurants', 'discounts', 'coupon']) AS t(name)
    WHERE to_regclass(name) IS NULL;

    -- Users
    CREATE TABLE IF NOT EXISTS users (
        user_id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_first_name VARCHAR(255) NOT NULL,
        user_second_name VARCHAR(255),
        user_last_name  VARCHAR(255) NOT NULL,
        user_birthday   DATE NOT NULL,
        user_join_date  TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
        user_email      VARCHAR(255) NOT NULL UNIQUE,
        user_password_hash VARCHAR(255) NOT NULL
    );

    -- Restaurants
    CREATE TABLE IF NOT EXISTS restaurants (
        restaurant_id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        restaurant_name          VARCHAR(255) NOT NULL,
        restaurant_owner_id      INT NOT NULL REFERENCES users(user_id) ON UPDATE CASCADE ON DELETE RESTRICT,
        restaurant_description   TEXT,
        restaurant_full_address  VARCHAR(255) NOT NULL,
        restaurant_creation_date TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
    );

    -- Discounts (promotions)
    CREATE TABLE IF NOT EXISTS discounts (
        discount_id                     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        discount_restaurant_id          INT NOT NULL REFERENCES restaurants(restaurant_id) ON UPDATE CASCADE ON DELETE RESTRICT,
        discount_view_amount            INT NOT NULL DEFAULT 0 CHECK (discount_view_amount >= 0),
        discount_name                   VARCHAR(255) NOT NULL,
        discount_status                 discount_status_enum NOT NULL DEFAULT 'Active',
        discount_applicable_products    TEXT NOT NULL,
        discount_type                   discount_type_enum NOT NULL,
        discount_amount                 NUMERIC(10,2),
        discount_customer_takes_amount  INT,
        discount_customer_pays_amount   INT,
        discount_start_timestamp        TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
        discount_end_timestamp          TIMESTAMPTZ,
        discount_max_uses               INT CHECK (discount_max_uses > 0),
        discount_max_use_amount_per_user INT CHECK (discount_max_use_amount_per_user > 0),
        discount_image_url              VARCHAR(255),
        discount_additional_use_conditions TEXT,

        -- IXJ requires takes/pays fields with takes > pays
        CHECK (discount_type <> 'IXJ' OR (
            discount_customer_takes_amount IS NOT NULL AND discount_customer_pays_amount IS NOT NULL
            AND discount_customer_takes_amount > discount_customer_pays_amount
            AND discount_customer_pays_amount >= 1
        )),
        -- Non-IXJ must not have takes/pays fields
        CHECK (discount_type = 'IXJ' OR (
            discount_customer_takes_amount IS NULL AND discount_customer_pays_amount IS NULL
        )),
        -- Amount validation per type
        CHECK (
            (discount_type = 'IXJ' AND discount_amount IS NULL)
            OR (discount_type = 'PERCENTAGE' AND discount_amount > 0 AND discount_amount <= 100)
            OR (discount_type = 'FIXED_VALUE' AND discount_amount > 0)
        ),
        -- End must be after start
        CHECK (discount_end_timestamp IS NULL OR discount_end_timestamp > discount_start_timestamp),
        -- At least one bound: end date or max uses (RN-09)
        CHECK (discount_end_timestamp IS NOT NULL OR discount_max_uses IS NOT NULL)
    );

    -- Coupon (without coupon_hash — added in V2)
    CREATE TABLE IF NOT EXISTS coupon (
        coupon_id                    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id                      INT NOT NULL REFERENCES users(user_id) ON UPDATE CASCADE ON DELETE RESTRICT,
        discount_id                  INT NOT NULL REFERENCES discounts(discount_id) ON UPDATE CASCADE ON DELETE RESTRICT,
        coupon_status                coupon_status_enum NOT NULL DEFAULT 'UNUSED',
        coupon_claim_timestamp       TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
        coupon_redemption_timestamp  TIMESTAMPTZ,

        -- USED coupons must have redemption timestamp >= claim
        CHECK (
            (coupon_status = 'UNUSED' AND coupon_redemption_timestamp IS NULL)
            OR (coupon_status = 'USED' AND coupon_redemption_timestamp IS NOT NULL
                AND coupon_redemption_timestamp >= coupon_claim_timestamp)
        )
    );

    FOREACH table_name IN ARRAY COALESCE(new_tables, ARRAY[]::text[]) LOOP
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', table_name);
    END LOOP;
END $$;
