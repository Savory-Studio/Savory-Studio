-- Authorized staff per restaurant.
-- The owner is already in restaurants.restaurant_owner_id;
-- this table tracks additional authorized personnel.
CREATE TABLE IF NOT EXISTS restaurant_staff (
    staff_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         INT NOT NULL REFERENCES users(user_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    restaurant_id   INT NOT NULL REFERENCES restaurants(restaurant_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    assigned_at     TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_staff_user_restaurant UNIQUE (user_id, restaurant_id)
);

ALTER TABLE restaurant_staff ENABLE ROW LEVEL SECURITY;
